    private void jButtonProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonProcessActionPerformed
        // TODO add your handling code here:
        try {
            String customerName = txtCustomerName.getText().trim();
            String selectedProduct = (String) cmbProducts.getSelectedItem();
            String priceText = txtPrice.getText().trim();

            if (customerName.isEmpty() || priceText.isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                    "Please fill in all fields.", 
                    "Input Error", 
                    JOptionPane.ERROR_MESSAGE);
                return;
            }

            double price = Double.parseDouble(priceText);

            //ProductCalculations class for calculations
            ProductCalculations calculations = new ProductCalculations(price);
            double vat = calculations.GetVat();
            double commission = calculations.GetCommission();
            double total = calculations.GetTotal();

            String message = String.format(
                "Customer Name: %s\nProduct: %s\nVAT: R %.1f\nCOMMISSION: R %.1f\nTOTAL: R %.1f",
                customerName, selectedProduct, vat, commission, total
            );

            JOptionPane.showMessageDialog(this, message, "Message", JOptionPane.INFORMATION_MESSAGE);

            // Save to data.txt
            saveToFile(customerName, selectedProduct, vat, commission, total);

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, 
                "Please enter a valid numeric value for the price.", 
                "Invalid Price", 
                JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jButtonProcessActionPerformed

